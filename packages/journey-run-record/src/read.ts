import { normalizeV1Run, normalizeV1Test } from "./legacy.js";
import { validateHref } from "./paths.js";
import { runRecordFormat, runRecordVersion, testRecordFormat, type RunRecord, type SuiteRun, type TestRecord } from "./types.js";

/** Reads the bytes of a file of a run directory; `href` is relative to the run directory. */
export type RunReader = (href: string) => Promise<Uint8Array>;
export type RunRecordHandle = Readonly<{ run: RunRecord; loadTest(id: string): Promise<TestRecord> }>;

const json = async (read: RunReader, href: string): Promise<unknown> => {
  validateHref(href);
  return JSON.parse(new TextDecoder().decode(await read(href)));
};

/** Versions the reader accepts. Version 1 is normalized in memory, so callers only see version 2. */
const readableVersions: readonly number[] = [1, runRecordVersion];

/** Open `run.json`; test records load on demand. Works with filesystem reads and HTTP fetches. */
export async function openRunRecord(read: RunReader): Promise<RunRecordHandle> {
  const raw = await json(read, "run.json") as { format?: unknown; version?: unknown; tests?: unknown } | null;
  if (raw?.format !== runRecordFormat || !readableVersions.includes(raw.version as number) || !Array.isArray(raw.tests)) {
    throw new Error(`Expected a Journey Mesh run record (run.json, version ${readableVersions.join(" or ")}). Reports written by older versions must be regenerated by running the suite again.`);
  }
  const version = raw.version as number;
  const run = version === 1 ? normalizeV1Run(raw) : raw as RunRecord;
  return {
    run,
    async loadTest(id) {
      const entry = run.tests.find((item) => item.id === id);
      if (!entry) throw new Error(`Unknown test ${id}`);
      const test = await json(read, entry.href) as { format?: unknown; version?: unknown; id?: unknown } | null;
      // A test record has the version of the run that wrote it.
      if (test?.format !== testRecordFormat || test.version !== version || test.id !== id) throw new Error(`Invalid test record for ${id}`);
      return version === 1 ? normalizeV1Test(test) : test as TestRecord;
    }
  };
}

/** Load every test record of a run. */
export async function loadSuiteRun(read: RunReader): Promise<SuiteRun> {
  const { run, loadTest } = await openRunRecord(read);
  const { format: _format, version: _version, tests: entries, ...summary } = run;
  const tests: TestRecord[] = [];
  for (const entry of entries) tests.push(await loadTest(entry.id));
  return { ...summary, tests };
}
